"""Right-size defender delivery from preserved sources; no drawing or rig changes.

Run from web/: python3 scripts/prepare-delivery-1.1.py
Uses the existing Pillow/libwebp toolchain. Historical conversion records stay intact.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageChops, __version__ as pillow_version, features

ROOT = Path(__file__).resolve().parents[1]
NAMES = ["ranger", "money-bush", "asteroid", "moon-zeus", "startrell-cluggins",
         "tars", "explosive-astro-joe", "money-tree", "frontier-flagship-compact"]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    previous = json.loads((ROOT / "art-source/expedition-0.5/derivatives.json").read_text())
    records, geometry = [], {}
    for name in NAMES:
        old = next(row for row in previous["assets"] if Path(row["file"]).stem == name)
        source, destination = ROOT / old["source"], ROOT / old["file"]
        if sha(source) != old["sourceSha256"]:
            raise ValueError(f"Preserved source changed: {source}")
        image = Image.open(source).convert("RGBA")
        image.thumbnail((192, 192), Image.Resampling.LANCZOS)
        image.save(destination, format="WEBP", quality=90, method=6,
                   exact=True, alpha_quality=100)
        decoded = Image.open(destination).convert("RGBA")
        if decoded.size != image.size or ImageChops.difference(
                decoded.getchannel("A"), image.getchannel("A")).getbbox():
            raise ValueError(f"Delivery alpha/geometry changed: {name}")
        bounds = image.getchannel("A").point(lambda value: 255 if value >= 32 else 0).getbbox()
        if not bounds or bounds[0] < 1 or bounds[1] < 1 or bounds[2] >= image.width or bounds[3] >= image.height:
            raise ValueError(f"Empty or clipped defender: {name}")
        foot = bounds[3] / image.height
        geometry[name] = {"size": list(image.size), "foot": foot}
        records.append({**old, "size": list(image.size), "maximum": 192,
                        "bytes": destination.stat().st_size, "sha256": sha(destination),
                        "alphaBounds32": bounds, "foot": foot,
                        "previousBytes": old["bytes"], "previousSha256": old["sha256"]})
    record = {"baseline": "b0ece92e4284ccb9919e5368cd18049a4d76a251",
              "pillow": pillow_version, "libwebp": features.version("webp"),
              "operation": "192px proportional LANCZOS from preserved PNG; unchanged WebP quality90/method6/exact/alpha_quality100",
              "scriptSha256": sha(Path(__file__)), "assets": records}
    target = ROOT / "art-source/expedition-1.1"
    target.mkdir(parents=True, exist_ok=True)
    (target / "defender-delivery.json").write_text(json.dumps(record, indent=2) + "\n")
    (ROOT / "src/game/defender-delivery.ts").write_text(
        "// Generated by scripts/prepare-delivery-1.1.py; do not edit.\n"
        + "export const DEFENDER_DELIVERY = " + json.dumps(geometry, indent=2)
        + " as const;\n")
    print(json.dumps({"defenders": len(records), "beforeBytes": sum(r["previousBytes"] for r in records),
                      "afterBytes": sum(r["bytes"] for r in records)}))


if __name__ == "__main__":
    main()
